// Ответы терминала на запросы приложения (xterm авто-отвечает на них через onData:
// CPR, DA, DSR, OSC-цвет). В интерактивной сессии они нужны программе, но во время
// логина tsh задержка Electron доставляет их в stdin уже поверх читаемого пароля —
// и портят его. Клавиатура человека таких последовательностей не порождает, поэтому
// на auth-фазе их безопасно вырезать из ввода в PTY. См. docs/04 §7 и ADR-0002.
const REPORT_RE = new RegExp(
  [
    '\\x1b\\[[0-9;]*R', // CPR — ответ на запрос позиции курсора (DSR 6n)
    '\\x1b\\[\\?[0-9;]*c', // DA1 — первичные атрибуты устройства
    '\\x1b\\[>[0-9;]*c', // DA2 — вторичные атрибуты
    '\\x1b\\[[0-9;]*n', // DSR — статус устройства
    '\\x1b\\][0-9]+;[^\\x07\\x1b]*(?:\\x07|\\x1b\\\\)' // OSC-ответы (цвет фона/текста и т.п.)
  ].join('|'),
  'g'
)

export const stripTerminalReports = (s: string): string => s.replace(REPORT_RE, '')
